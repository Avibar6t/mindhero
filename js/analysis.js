// MindHero – ניתוח מקצועי להורים: פענוח משימת הגילוי וההתקדמות שאחריה
import { CHAPTERS, CH_ORDER } from './bank.js?v=18';

const SKILL = {
  verbal: { what: 'אוצר מילים, הבנת משמעויות של מילים בהקשר וקשרים לוגיים במשפט (למרות, לכן, אלא).', home: 'קריאה משותפת ושיחה על מילים עם כמה משמעויות ("עין", "קרן"). כשמופיעה מילה לא מוכרת – לנחש את המשמעות מההקשר לפני שבודקים.' },
  series: { what: 'זיהוי חוקיות במספרים ובאותיות: הפרשים, כפל, וסדרות משולבות.', home: 'משחקי "מה הבא?" בדרך: אתם אומרים 3 מספרים, הוא מגלה את החוק – ואז הוא ממציא סדרה בשבילכם.' },
  analogy: { what: 'הבנת יחסים בין מושגים (חלק-שלם, כלי-שימוש, סיבה-תוצאה) ודיוק בניסוח הקשר.', home: 'משחק "מה הקשר?": בוחרים שני דברים ומנסחים משפט שמחבר ביניהם. מעודד דיוק ולא רק "הם קשורים".' },
  logic: { what: 'הסקת מסקנות, עבודה עם תנאים, סידורים ומשפטי "בהכרח".', home: 'שחמט (שהוא כבר אוהב) מאמן בדיוק את זה, וגם חידות היגיון. עוזר מאוד להרגיל אותו לצייר טבלה או סקיצה.' },
  math: { what: 'בעיות מילוליות, אחוזים, ממוצעים ופעולות מומצאות, כמו <span class="ltrm">a ★ b</span>.', home: 'חשבון בעל-פה מחיי היום-יום: הנחות בחנות, זמני נסיעה. ולעודד אותו לבדוק תשובה בהצבה חזרה בשאלה.' },
  shapes: { what: 'חשיבה חזותית: מציאת חוקיות בצורה, צבע, כמות וסיבוב במטריצה.', home: 'כאן גיימרים מתחילים מיתרון. הטיפ המרכזי: לבדוק תכונה אחת בכל פעם, לאורך שורה ואז לאורך עמודה.' },
};
const band = s => s >= 16 ? ['גבוה מאוד', 'ביצועים מצוינים כבר בנקודת הפתיחה. האימון יתמקד בשאלות ברמות הקושי הגבוהות ובניהול זמן.']
  : s >= 12 ? ['גבוה', 'בסיס חזק. ההכנה תחדד את הפרקים החלשים יחסית ותבנה מהירות וביטחון.']
  : s >= 7 ? ['בינוני', 'בסיס טוב עם פערים ברורים בין הפרקים – בדיוק המצב שבו אימון ממוקד עושה את ההבדל הגדול ביותר.']
  : ['התחלתי', 'רוב סוגי השאלות עוד חדשים לו. זה טבעי בשלב הזה – ההיכרות עם סוגי השאלות לבדה מעלה משמעותית את הביצועים.'];
const lvlWord = n => n === 3 ? 'חוזקה' : n === 2 ? 'טוב' : n === 1 ? 'לחיזוק' : 'עדיפות ראשונה';

export function analysisHTML(p, ic) {
  if (!p.diagResult) return '';
  const per = p.diagResult.per; const total = CH_ORDER.reduce((s, c) => s + (per[c] || 0), 0);
  const [bName, bText] = band(total);
  const strong = CH_ORDER.filter(c => per[c] >= 3), weak = CH_ORDER.filter(c => (per[c] || 0) <= 1).sort((a, b) => per[a] - per[b]);
  const r = p.records || {};
  const lines = [];
  // התקדמות מאז הגילוי
  const prog = CH_ORDER.map(c => ({ c, base: 1.5 + (per[c] || 0), now: p.ch?.[c]?.lvl || 0, n: p.ch?.[c]?.n || 0 })).filter(x => x.n >= 13);
  const up = prog.filter(x => x.now - x.base >= 0.5), down = prog.filter(x => x.base - x.now >= 0.5);
  if (up.length) lines.push(`<b>התקדמות מאז משימת הגילוי:</b> שיפור ברור ב${up.map(x => CHAPTERS[x.c].name).join(', ')}.`);
  if (down.length) lines.push(`ב${down.map(x => CHAPTERS[x.c].name).join(', ')} הרמה ירדה מעט מאז הגילוי – לרוב זה סימן שהמערכת הגיעה לשאלות קשות יותר, וזה חלק תקין מהלמידה.`);
  // קצב
  if (r.totalQ >= 30 && r.qTime) {
    const avg = r.qTime / r.totalQ;
    if (avg > 95) lines.push(`<b>קצב:</b> בממוצע ${Math.round(avg)} שניות לשאלה. במבחן יש בערך דקה וחצי לשאלה, אז כדאי לשלב יותר קרבות בוס וסימולציות עם שעון.`);
    else if (avg < 25 && r.totalOk / r.totalQ < 0.55) lines.push(`<b>קצב:</b> ${Math.round(avg)} שניות לשאלה ודיוק נמוך יחסית – נראה שהוא ממהר. כדאי לעודד אותו לקרוא את השאלה עד הסוף לפני שבוחר.`);
    else lines.push(`<b>קצב:</b> ${Math.round(avg)} שניות לשאלה בממוצע – קצב שמתאים לזמן במבחן.`);
  }
  // רמזים
  if (r.totalQ >= 30) {
    const hr = (r.hints || 0) / r.totalQ;
    if (hr > 0.8) lines.push('<b>רמזים:</b> משתמש ברמזים כמעט בכל שאלה. זה טוב ללמידה, אבל כדאי לעודד אותו לנסות קודם לבד דקה לפני שהוא מבקש רמז – במבחן אין רמזים.');
    else if (hr < 0.05 && r.totalOk / r.totalQ < 0.5) lines.push('<b>רמזים:</b> כמעט לא משתמש ברמזים, למרות שהרבה תשובות שגויות. כדאי להזכיר לו שהרמז הראשון לא מגלה תשובה – רק מכוון.');
  }
  // סימולציות
  const sims = r.sims || [];
  if (sims.length) { const last = sims[sims.length - 1]; if (last.empty) lines.push(`<b>סימולציה אחרונה:</b> נשארו ${last.empty} שאלות ריקות. במבחן אין עונש על טעות, ולכן חשוב לחזור איתו על הכלל "לא משאירים שאלה ריקה".`); if (sims.length >= 2) { const d = last.score - sims[sims.length - 2].score; if (Math.abs(d) >= 5) lines.push(`בין שתי הסימולציות האחרונות ${d > 0 ? 'עלייה' : 'ירידה'} של ${Math.abs(d)} נקודות.`); } }

  return `<div class="p-card rec"><h4>${ic('bulb')} ניתוח מקצועי</h4>
    <p><b>רמת פתיחה: ${bName}</b> (${total}/18 במשימת הגילוי). ${bText}</p>
    <div class="ana-grid">${CH_ORDER.map(c => `<div class="ana" style="--c:${CHAPTERS[c].color}"><div class="ana-h">${ic(c)}<b>${CHAPTERS[c].name}</b><span class="ana-tag t${per[c] || 0}">${lvlWord(per[c] || 0)}</span></div><small>${SKILL[c].what}</small></div>`).join('')}</div>
    ${strong.length ? `<p><b>נקודות חוזק:</b> ${strong.map(c => CHAPTERS[c].name).join(', ')}. כדאי להגיד לו את זה במפורש – ביטחון בפרק אחד עוזר בכל המבחן.</p>` : ''}
    ${weak.length ? `<p><b>איך לעזור בבית:</b></p><ul>${weak.slice(0, 3).map(c => `<li><b>${CHAPTERS[c].name}:</b> ${SKILL[c].home}</li>`).join('')}</ul>` : ''}
    ${lines.length ? `<p><b>מה רואים מאז:</b></p><ul>${lines.map(l => `<li>${l}</li>`).join('')}</ul>` : '<p class="muted small">אחרי עוד כמה ימי אימון יופיע כאן גם ניתוח של קצב, שימוש ברמזים והתקדמות לעומת נקודת הפתיחה.</p>'}
    <p class="muted small">חשוב לזכור: 18 שאלות הן מדגם קצר. הניתוח מתאר נקודת פתיחה ומגמות באימון, ולא מנבא את תוצאת המבחן.</p></div>`;
}
