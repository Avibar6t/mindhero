export function genVerbal(diff, seed) {
  const r = rng(seed);
  const kinds = diff <= 2 ? ['syn', 'ant', 'odd'] : diff === 3 ? ['syn', 'ant', 'odd', 'tricky'] : ['syn', 'ant', 'tricky', 'tricky'];
  const kind = pick(r, kinds);
  if (kind === 'syn' || kind === 'ant') {
    const e = pick(r, WORDS); const syn = kind === 'syn';
    const right = syn ? e.s : e.a, trap = syn ? e.a : e.s;
    const rest = shuffle(r, WORDS.filter(x => x !== e)).slice(0, 2).map(x => pick(r, [x.w, x.s, x.a]));
    const set = new Set([right]); if (diff >= 2) set.add(trap);
    rest.forEach(x => { if (x !== e.w) set.add(x); });
    for (const x of shuffle(r, WORDS)) { if (set.size >= 4) break; if (x !== e && x.w !== e.w) set.add(x.w); }
    const opts = [...set].slice(0, 4);
    return {
      id: uid(r, 'v'), ch: 'verbal', diff, type: 'mc', gen: true,
      q: syn ? `איזו מילה <b>קרובה ביותר במשמעותה</b> למילה:<div class="qsent">${e.w}</div>` : `איזו מילה היא <b>ההפך</b> של המילה:<div class="qsent">${e.w}</div>`,
      opts, ans: 0,
      hints: [syn ? `נסו לשים כל תשובה במשפט במקום "${e.w}". איזו מילה שומרת על אותה משמעות?` : `חשבו על משפט עם "${e.w}" – איזו מילה הופכת את המשמעות שלו?`,
        diff >= 2 ? `זהירות: אחת התשובות היא ${syn ? 'דווקא ההפך' : 'דווקא מילה דומה'} – היא קשורה למילה, אבל לא מה ששואלים.` : `התשובה מתחילה באות "${right[0]}".`],
      exp: syn ? `"${right}" ו"${e.w}" אומרות כמעט אותו דבר. "${trap}" היא ההפך של "${e.w}".` : `"${right}" היא ההפך של "${e.w}". "${trap}" דווקא דומה ל"${e.w}".`,
      rule: syn ? 'מילה נרדפת = מילה שאפשר להחליף בה את המילה במשפט, והמשמעות נשארת.' : 'הפך = מילה שהופכת את המשמעות של המשפט.',
      steps: [`בונים משפט קצר עם "${e.w}".`, `מחליפים בו את "${e.w}" ב"${right}" – ${syn ? 'המשמעות נשארת' : 'המשמעות מתהפכת'}.`, `"${trap}" היא מלכודת: ${syn ? 'היא ההפך' : 'היא בעלת משמעות דומה'}.`],
      tip: 'בשאלות מילים תמיד יש מסיח שהוא "כמעט נכון" – ההפך במקום הנרדפת, או להפך. קוראים שוב את השאלה לפני שבוחרים.',
    };
  }
  if (kind === 'odd') {
    const names = Object.keys(CATS); const c1 = pick(r, names); const c2 = pick(r, names.filter(x => x !== c1));
    const three = shuffle(r, CATS[c1]).slice(0, diff <= 1 ? 3 : 4); const odd = pick(r, CATS[c2]);
    return {
      id: uid(r, 'v'), ch: 'verbal', diff, type: 'mc', gen: true,
      sig: `odd:${c1}:${odd}`, q: 'איזו מילה <b>לא שייכת</b> לקבוצה?', opts: [odd, ...three].slice(0, 5), ans: 0,
      hints: ['מצאו מה משותף לרוב המילים – לאיזו קבוצה הן שייכות?', `רוב המילים הן ${c1}.`],
      exp: `${three.join(', ')} – כולם ${c1}. "${odd}" שייך לקבוצה אחרת: ${c2}.`,
      rule: 'מוצאים את <b>הקבוצה המשותפת</b> לרוב המילים, ואז מחפשים את המילה שלא נכנסת אליה.',
      steps: [`מה משותף ל${three.slice(0, 2).join(' ול')}? הם ${c1}.`, `בודקים כל מילה: רק "${odd}" לא שייך ל${c1} – הוא מתוך ${c2}.`],
      tip: 'אם נראה שיש שתי מילים יוצאות דופן – מחפשים קבוצה מדויקת יותר שמתאימה לכל השאר.',
    };
  }
  const t = pick(r, TRICKY); const four = shuffle(r, t.set).slice(0, 4);
  return {
    id: uid(r, 'v'), ch: 'verbal', diff, type: 'mc', gen: true,
    sig: `trk:${t.odd}`, q: 'איזו מילה <b>לא שייכת</b> לקבוצה?', opts: [t.odd, ...four], ans: 0,
    hints: ['במבט ראשון כולן נראות שייכות. חפשו תכונה מדויקת יותר שמשותפת לכולן חוץ מאחת.', 'חשבו על מדע, מספרים או מבנה – לא רק על איפה הדברים נמצאים.'],
    exp: t.why, rule: 'בשאלות "יוצא דופן" קשות, התשובה נראית שייכת. מחפשים את <b>התכונה המדויקת</b> שמשותפת לכל השאר.',
    steps: [`הקבוצה: ${four.join(', ')}, ${t.odd}.`, t.why],
    tip: 'כשכל המילים נראות שייכות – שאלו "מה הסוג המדעי / המספרי / המבני של כל אחת?"',
  };
}

