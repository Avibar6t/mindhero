// יחסים קרובים מדי – לא משמשים כמסיחים זה לזה
const NEAR = { group: ['part'], part: ['group'], place: ['home', 'worker'], home: ['place'], worker: ['place', 'maker'], maker: ['worker', 'material'], material: ['maker'], tool: ['measure', 'worker'], measure: ['tool'] };
const AQ = (a, b) => `מצאו את הזוג שהקשר בין המילים בו <b>הכי דומה</b> לקשר בין המילים:<div class="qsent">${a} : ${b}</div>`;

export function genAnalogy(diff, seed) {
  const r = rng(seed);
  const keys = Object.keys(REL).filter(k => REL[k].d <= Math.max(1, diff) && (diff <= 2 || REL[k].d >= Math.min(3, diff - 1)));
  const k = pick(r, keys), R = REL[k];
  const [p1, p2] = shuffle(r, R.pairs);
  const used = new Set([...p1, ...p2]);
  const others = shuffle(r, Object.keys(REL).filter(x => x !== k && !(NEAR[k] || []).includes(x)));
  const opts = [`${p2[0]} : ${p2[1]}`];
  const dExp = [];
  // מסיח "הפוך" ברמות הגבוהות (מלכודת קלאסית)
  if (diff >= 3 && !R.sym) { const p3 = R.pairs.find(p => !used.has(p[0]) && !used.has(p[1])); if (p3) { opts.push(`${p3[1]} : ${p3[0]}`); p3.forEach(w => used.add(w)); dExp.push(`"${p3[1]} : ${p3[0]}" – אותן מילים אבל <b>בסדר הפוך</b>. הסדר חשוב!`); } }
  for (const o of others) {
    if (opts.length >= 4) break;
    const cand = shuffle(r, REL[o].pairs).find(p => !used.has(p[0]) && !used.has(p[1]));
    if (!cand) continue;
    cand.forEach(w => used.add(w)); opts.push(`${cand[0]} : ${cand[1]}`);
    dExp.push(`"${cand[0]} : ${cand[1]}" – כאן הקשר אחר: ${REL[o].s(cand[0], cand[1])}.`);
  }
  const [a, b] = p1;
  return {
    id: uid(r, 'a'), ch: 'analogy', diff, type: 'mc', gen: true,
    q: AQ(a, b), opts, ans: 0,
    hints: [`נסחו משפט שמחבר בין "${a}" ל"${b}", ואז בדקו את אותו משפט על כל זוג.`, `המשפט המחבר: "${R.rel}".`],
    exp: `${R.s(a, b)}, ובדיוק כך ${R.s(p2[0], p2[1])}.`,
    rule: `בונים <b>משפט מקשר</b> לזוג הראשון: "${R.rel}". הזוג הנכון הוא היחיד שאותו משפט עובד עליו, באותו סדר.`,
    steps: [`המשפט המקשר: ${R.s(a, b)}.`, `בודקים אותו על כל זוג. רק ב"${p2[0]} : ${p2[1]}" הוא עובד: ${R.s(p2[0], p2[1])}.`, ...dExp],
    tip: 'אם המשפט שלכם מתאים ליותר מזוג אחד – הוא כללי מדי. הופכים אותו למדויק יותר ובודקים שוב.',
  };
}

